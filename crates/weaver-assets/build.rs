//! Embeds the account SPA and the vendored ALTCHA widget into the binary, with
//! gzip and zstd variants pre-compressed here, at build time.
//!
//! The SvelteKit build output — a static shell plus hashed assets — is produced
//! *before* cargo compiles the server (see the CI workflow), and embedded as
//! `include_bytes!` entries. The ALTCHA widget additionally gets a content
//! version derived from every file, which versions its asset URLs.
//!
//! Pre-compressing here keeps all compression cost out of the relay: every asset
//! is stored identity-encoded and, when its type benefits, once gzipped and once
//! zstd-framed. The edge then picks a variant from `Accept-Encoding` (see
//! `negotiate_encoding`). The compressed bytes are written under `OUT_DIR` and
//! pulled in with `include_bytes!`, so nothing extra lands next to the binary.
//! Each variant is decoded back and compared here, so a corrupt variant fails
//! the build rather than a user's request.
//!
//! When the `account-spa` feature is off — which is how `weave` links this
//! crate — no SPA table is emitted at all, so the client never carries SPA
//! bytes and a Node-less build of the client still compiles. When it is on, a
//! missing SPA build is a hard error naming the command to run.

use std::fs;
use std::io::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=WEAVER_SPA_DIR");

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR is set by cargo"));
    let dest = out_dir.join("assets.rs");
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));

    let enabled = std::env::var_os("CARGO_FEATURE_ACCOUNT_SPA").is_some();
    // Default to the repo-level `frontend/build`; overridable for out-of-tree
    // builds and tests.
    let root = std::env::var("WEAVER_SPA_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|_| manifest.join("../../frontend/build"));

    let mut out = String::from("// Generated by build.rs — do not edit.\n");
    let mut compressor = Compressor::new(out_dir.join("compressed"));

    // ---- the account SPA (only with the feature) -------------------------
    if enabled {
        let shell = root.join("index.html");
        if !shell.is_file() {
            panic!(
                "the `account-spa` feature is enabled but the account SPA has not been built.\n\
                 \n\
                 Build it first, then re-run this command:\n\
                 \n    pnpm --dir frontend run build\n\
                 \n\
                 Expected a built shell at: {}\n\
                 (Set WEAVER_SPA_DIR to embed a build from a different directory.)",
                normalize(&shell).display()
            );
        }
        println!("cargo:rerun-if-changed={}", root.display());
        let files = collect(&root, &|_| true);
        emit_table(&mut out, "SPA_ASSETS", "spa", &files, &mut compressor);
    }

    // ---- the vendored ALTCHA widget (always embedded) --------------------
    let altcha_root = manifest.join("static/altcha");
    println!("cargo:rerun-if-changed={}", altcha_root.display());
    // Only the files the widget actually loads; the directory also holds
    // provenance notes we must not ship.
    let altcha = collect(&altcha_root, &|name| {
        name.ends_with(".js") || name.ends_with(".css")
    });
    emit_table(
        &mut out,
        "ALTCHA_ASSETS",
        "altcha",
        &altcha,
        &mut compressor,
    );
    out.push_str(&format!(
        "pub(crate) const ALTCHA_ASSET_VERSION: &str = {:?};\n",
        format!("{:016x}", content_version(&altcha))
    ));

    fs::write(&dest, out).expect("write generated asset table");
}

/// Emits `pub(crate) static <name>: &[AssetRow]`, one row per file with its
/// pre-compressed variants.
fn emit_table(
    out: &mut String,
    name: &str,
    namespace: &str,
    files: &[(String, PathBuf, &'static str)],
    compressor: &mut Compressor,
) {
    out.push_str(&format!("pub(crate) static {name}: &[AssetRow] = &[\n"));
    for (file, path, content_type) in files {
        let bytes = fs::read(path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
        let variants = compressor.variants(namespace, content_type, &bytes);
        out.push_str(&format!(
            "    ({file:?}, include_bytes!({:?}), {content_type:?}, {}, {}),\n",
            path.to_string_lossy(),
            field(&variants.gzip),
            field(&variants.zstd)
        ));
    }
    out.push_str("];\n");
}

/// Pre-compresses assets into `OUT_DIR/compressed`, once each.
struct Compressor {
    dir: PathBuf,
    sequence: usize,
}

/// The `include_bytes!` expressions for an asset's compressed variants.
struct Variants {
    gzip: Option<String>,
    zstd: Option<String>,
}

impl Compressor {
    fn new(dir: PathBuf) -> Self {
        fs::create_dir_all(&dir).expect("create the compressed asset directory");
        Self { dir, sequence: 0 }
    }

    /// Compresses one asset, writing `.gz`/`.zst` siblings and returning the
    /// `include_bytes!` expressions. Types that do not compress get no variants.
    fn variants(&mut self, namespace: &str, content_type: &str, bytes: &[u8]) -> Variants {
        if !compressible(content_type) || bytes.is_empty() {
            return Variants {
                gzip: None,
                zstd: None,
            };
        }
        let sequence = self.sequence;
        self.sequence += 1;

        let gzip = gzip(bytes);
        let zstd = zstd_frame(bytes);
        // A variant that does not decode back to the original is a build bug,
        // not a runtime one: fail here, where the cause is obvious.
        assert_eq!(gunzip(&gzip), bytes, "gzip variant does not round-trip");
        assert_eq!(unzstd(&zstd), bytes, "zstd variant does not round-trip");

        let gzip_path = self.dir.join(format!("{namespace}-{sequence:04}.gz"));
        let zstd_path = self.dir.join(format!("{namespace}-{sequence:04}.zst"));
        fs::write(&gzip_path, &gzip).expect("write gzip variant");
        fs::write(&zstd_path, &zstd).expect("write zstd variant");

        Variants {
            gzip: Some(include_bytes_expr(&gzip_path)),
            zstd: Some(include_bytes_expr(&zstd_path)),
        }
    }
}

/// `Some(include_bytes!("…"))`, or `None` when the asset has no such variant.
fn field(expression: &Option<String>) -> String {
    match expression {
        Some(expression) => format!("Some({expression})"),
        None => "None".to_string(),
    }
}

fn include_bytes_expr(path: &Path) -> String {
    format!("include_bytes!({:?})", path.to_string_lossy())
}

/// gzip at maximum level, with no embedded timestamp so the output is stable.
fn gzip(bytes: &[u8]) -> Vec<u8> {
    let mut encoder = flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::best());
    encoder.write_all(bytes).expect("gzip the asset");
    encoder.finish().expect("finish the gzip stream")
}

fn gunzip(bytes: &[u8]) -> Vec<u8> {
    use std::io::Read as _;
    let mut decoded = Vec::new();
    flate2::read::GzDecoder::new(bytes)
        .read_to_end(&mut decoded)
        .expect("decode the gzip variant");
    decoded
}

/// zstd at a high level; the cost is paid once, at build time.
fn zstd_frame(bytes: &[u8]) -> Vec<u8> {
    zstd::stream::encode_all(bytes, 19).expect("zstd the asset")
}

fn unzstd(frame: &[u8]) -> Vec<u8> {
    zstd::stream::decode_all(frame).expect("decode the zstd variant")
}

/// Whether a content type is worth compressing: text and code compress well,
/// while images, fonts and archives are already compressed (and would only grow).
fn compressible(content_type: &str) -> bool {
    let essence = content_type.split(';').next().unwrap_or("").trim();
    matches!(
        essence,
        "text/html"
            | "text/css"
            | "text/plain"
            | "text/javascript"
            | "application/javascript"
            | "application/json"
            | "image/svg+xml"
            | "application/wasm"
    )
}

/// FNV-1a over every embedded byte: any change to any asset changes the version,
/// which changes the immutable asset URLs and busts caches.
fn content_version(files: &[(String, PathBuf, &'static str)]) -> u64 {
    let mut version: u64 = 0xcbf2_9ce4_8422_2325;
    for (_, path, _) in files {
        let bytes = fs::read(path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
        for byte in bytes {
            version ^= u64::from(byte);
            version = version.wrapping_mul(0x0000_0100_0000_01b3);
        }
    }
    version
}

/// Recursively collects `(relative path, absolute path, content type)`, sorted
/// by relative path so the generated tables are deterministic.
fn collect(root: &Path, keep: &dyn Fn(&str) -> bool) -> Vec<(String, PathBuf, &'static str)> {
    let mut out = Vec::new();
    walk(root, root, keep, &mut out);
    out.sort_by(|a, b| a.0.cmp(&b.0));
    out
}

fn walk(
    root: &Path,
    dir: &Path,
    keep: &dyn Fn(&str) -> bool,
    out: &mut Vec<(String, PathBuf, &'static str)>,
) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            walk(root, &path, keep, out);
        } else if let Ok(relative) = path.strip_prefix(root) {
            let name = relative.to_string_lossy().replace('\\', "/");
            if keep(&name) {
                out.push((name, path.clone(), content_type(&path)));
            }
        }
    }
}

/// Collapses `.`/`..` segments so an error message can show a readable path
/// even when the target is absent (so `canonicalize` is not usable).
fn normalize(path: &Path) -> PathBuf {
    let mut out = PathBuf::new();
    for component in path.components() {
        match component {
            std::path::Component::ParentDir => {
                out.pop();
            }
            std::path::Component::CurDir => {}
            other => out.push(other.as_os_str()),
        }
    }
    out
}

/// A conservative content type for the asset extensions we embed.
fn content_type(path: &Path) -> &'static str {
    match path.extension().and_then(|e| e.to_str()) {
        Some("html") => "text/html; charset=utf-8",
        Some("js" | "mjs") => "text/javascript; charset=utf-8",
        Some("css") => "text/css; charset=utf-8",
        Some("json" | "map") => "application/json",
        Some("svg") => "image/svg+xml",
        Some("png") => "image/png",
        Some("jpg" | "jpeg") => "image/jpeg",
        Some("webp") => "image/webp",
        Some("avif") => "image/avif",
        Some("ico") => "image/x-icon",
        Some("woff2") => "font/woff2",
        Some("woff") => "font/woff",
        Some("ttf") => "font/ttf",
        Some("txt") => "text/plain; charset=utf-8",
        Some("wasm") => "application/wasm",
        _ => "application/octet-stream",
    }
}
