//! Embeds the built account SPA into the binary (WVR-36).
//!
//! The SvelteKit build output — a static shell plus hashed assets — is produced
//! *before* cargo compiles the server (see the CI workflow), and embedded here
//! as `include_bytes!` entries with a content version derived from every file.
//!
//! When the `account-spa` feature is off, or the output directory is missing
//! (a plain `cargo build` without Node), this still emits a file defining an
//! empty asset map and a placeholder shell, so the workspace always compiles.
//! That is what lets `weave` (which links this crate with default features off)
//! and a Node-less dev environment build the crate unchanged.

use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=WEAVER_SPA_DIR");

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR is set by cargo"));
    let dest = out_dir.join("spa_assets.rs");

    let enabled = std::env::var_os("CARGO_FEATURE_ACCOUNT_SPA").is_some();
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    // Default to the repo-level `frontend/build`; overridable for out-of-tree
    // builds and tests.
    let root = std::env::var("WEAVER_SPA_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|_| manifest.join("../../frontend/build"));

    if !enabled || !root.join("index.html").is_file() {
        fs::write(&dest, placeholder()).expect("write placeholder spa_assets.rs");
        return;
    }

    println!("cargo:rerun-if-changed={}", root.display());

    let mut files: Vec<(String, PathBuf, &'static str)> = Vec::new();
    walk(&root, &root, &mut files);
    files.sort_by(|a, b| a.0.cmp(&b.0));

    // FNV-1a over every embedded byte: any change to any asset changes the
    // version, which changes the immutable asset URLs and busts caches.
    let mut version: u64 = 0xcbf2_9ce4_8422_2325;
    for (_, path, _) in &files {
        if let Ok(bytes) = fs::read(path) {
            for &byte in &bytes {
                version ^= u64::from(byte);
                version = version.wrapping_mul(0x0000_0100_0000_01b3);
            }
        }
    }

    let index = files
        .iter()
        .find(|(name, _, _)| name == "index.html")
        .map(|(_, path, _)| path.clone())
        .unwrap_or_else(|| root.join("index.html"));

    let mut out = String::from("// Generated by build.rs for WVR-36 — do not edit.\n");
    out.push_str("pub(crate) static SPA_ASSETS: &[(&str, &[u8], &str)] = &[\n");
    for (name, path, content_type) in &files {
        out.push_str(&format!(
            "    ({:?}, include_bytes!({:?}), {:?}),\n",
            name,
            path.to_string_lossy(),
            content_type
        ));
    }
    out.push_str("];\n");
    out.push_str(&format!(
        "pub(crate) static SPA_INDEX: &[u8] = include_bytes!({:?});\n",
        index.to_string_lossy()
    ));
    out.push_str(&format!(
        "pub(crate) const SPA_ASSET_VERSION: &str = {:?};\n",
        format!("{version:016x}")
    ));
    fs::write(&dest, out).expect("write spa_assets.rs");
}

/// Recursively collects `(relative path, absolute path, content type)`.
fn walk(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf, &'static str)>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            walk(root, &path, out);
        } else if let Ok(relative) = path.strip_prefix(root) {
            let name = relative.to_string_lossy().replace('\\', "/");
            out.push((name, path.clone(), content_type(&path)));
        }
    }
}

/// A conservative content type for the asset extensions a SvelteKit build emits.
fn content_type(path: &Path) -> &'static str {
    match path.extension().and_then(|e| e.to_str()) {
        Some("html") => "text/html; charset=utf-8",
        Some("js" | "mjs") => "text/javascript; charset=utf-8",
        Some("css") => "text/css; charset=utf-8",
        Some("json" | "map") => "application/json",
        Some("svg") => "image/svg+xml",
        Some("png") => "image/png",
        Some("jpg" | "jpeg") => "image/jpeg",
        Some("webp") => "image/webp",
        Some("avif") => "image/avif",
        Some("ico") => "image/x-icon",
        Some("woff2") => "font/woff2",
        Some("woff") => "font/woff",
        Some("ttf") => "font/ttf",
        Some("txt") => "text/plain; charset=utf-8",
        Some("wasm") => "application/wasm",
        _ => "application/octet-stream",
    }
}

/// The file written when no SPA is embedded.
fn placeholder() -> String {
    let shell = "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">\
                 <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\
                 <title>Tunnel Weaver</title></head><body>\
                 <p>The account app is not embedded in this build.</p></body></html>";
    format!(
        "// Generated by build.rs (placeholder) for WVR-36 — do not edit.\n\
         pub(crate) static SPA_ASSETS: &[(&str, &[u8], &str)] = &[];\n\
         pub(crate) static SPA_INDEX: &[u8] = {shell:?}.as_bytes();\n\
         pub(crate) const SPA_ASSET_VERSION: &str = \"placeholder\";\n"
    )
}
