//! `totp_credential` (WVR-166).
//!
//! One row per enrolled authenticator app, one-to-many with the account: the
//! table is shaped like `email_identity` (no uniqueness on `account_id`, an index
//! on the account, a cascade on delete) because an account may hold as many apps
//! as it likes.
//!
//! * `name` is never null: an empty string means "the person did not name it",
//!   and the console derives a label. It is also what the app itself displays
//!   beside the issuer, so two enrolled apps are told apart in the authenticator
//!   and not only in the console.
//! * `secret` is the shared secret sealed with the account TOTP key, `nonce ‖
//!   ciphertext` in hex. The store never sees the plaintext: it is handed a
//!   ciphertext and hands the same back, and only `account::totp` can open it.
//! * `confirmed_at` is null until a code generated by the app has been verified,
//!   which is what keeps a pending enrolment out of both sign-in and the ways up.
//!   A pending row is invisible everywhere — the console lists confirmed apps
//!   only — and is dropped by the account sweep once it is old (nothing but an
//!   abandoned dialog leaves one behind).
//! * `last_used_step` (with `last_used_at`) is the replay guard and is null until
//!   the first accepted code; it is deliberately a column and not memory, so a
//!   restart cannot make a burned code acceptable again.
//!
//! `account_id` cascades: this repo hard-deletes accounts and guarantees nothing
//! of them — least of all a second factor — survives.

