//! `totp_credential` table: the authenticator apps an account holds (WVR-166).
//!
//! One row per enrolled app, one-to-many with the account exactly like
//! `email_identity`: an account may hold as many as it likes and each row owns
//! its own secret, so removing one app stops that app's codes and nothing else.
//! Like `passkey_credential` this table is not append-only — removal is immediate
//! revocation — and unlike `email_identity` there is no uniqueness invariant to
//! enforce, because nothing ever looks a credential up by value.
//!
//! * `secret` is the app's shared secret, sealed with the account's TOTP key
//!   (`account.totp_key`), stored as `nonce ‖ ciphertext` in hex. The plaintext
//!   exists in exactly one place — the response to the enrolment that created it
//!   — and is never persisted or logged. The account id is bound in as
//!   associated data, so a sealed secret cannot be moved between accounts.
//! * `confirmed_at` is genuinely absent until a code the app generated has been
//!   verified. That is what keeps a half-finished enrolment from being either a
//!   way in or a second factor, and it is the same "a real absence" as
//!   `email_identity.verified_at`. A pending row is invisible everywhere — the
//!   console lists confirmed apps only — and the account sweep drops it once it
//!   is old.
//! * `name` is never null: an empty string means "the person did not name it",
//!   and the console derives a label. It is also the label the app displays
//!   beside the issuer, so two enrolled apps are told apart in the authenticator
//!   itself and not only in the console.
//! * `last_used_step` is the replay guard: the time step of the last accepted
//!   code, absent until the first one, advanced only when it moves forward. A
//!   code an attacker observed is therefore refused even across a restart.
//! * `last_used_at` is when that code was accepted, for the console to show.

use sea_orm::entity::prelude::*;

#[derive(Clone, Debug, PartialEq, Eq, DeriveEntityModel)]
#[sea_orm(table_name = "totp_credential")]
pub struct Model {
    #[sea_orm(primary_key)]
    pub id: i32,
    pub account_id: i32,
    /// What the person called it; empty means they did not name it.
    pub name: String,
    /// The shared secret, sealed with `account.totp_key` (`nonce ‖ ciphertext`, hex).
    pub secret: String,
    pub created_at: i64,
    /// When a code generated by this app was first verified; absent until then.
    pub confirmed_at: Option<i64>,
    /// When a code from this app was last accepted.
    pub last_used_at: Option<i64>,
    /// The time step of the last accepted code, for the replay guard.
    pub last_used_step: Option<i64>,
}

#[derive(Copy, Clone, Debug, EnumIter, DeriveRelation)]
pub enum Relation {
    #[sea_orm(
        belongs_to = "super::account::Entity",
        from = "Column::AccountId",
        to = "super::account::Column::Id",
        on_delete = "Cascade"
    )]
    Account,
}

impl Related<super::account::Entity> for Entity {
    fn to() -> RelationDef {
        Relation::Account.def()
    }
}

impl ActiveModelBehavior for ActiveModel {}
